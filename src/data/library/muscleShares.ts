// Sources behind the muscle shares (November 2026). The shares themselves come from
// targeting.json, imported from the muscle-targeting sheet by scripts/exercise-library.
import type { Citation } from '@/domain/analytics/citations';

export interface MuscleShare {
  /** Muscle region from the muscle-targeting sheet's key ("Mid chest (sternal pec)"). */
  region: string;
  /** Estimated share of the work, in percent, in 5% steps. The shares of an exercise add to 100. */
  share: number;
}

export type Laterality = 'bilateral' | 'unilateral' | 'both';

export interface ExerciseShares {
  regions: MuscleShare[];
  /** How sure the direction is (which muscles lead), not the exact numbers. */
  confidence: 'moderate' | 'low-moderate' | 'low';
  /** Studies behind it; empty when it is an expert estimate from the closest studied exercise. */
  sources: string[];
  /** The technique the estimate assumes, only when it is specific to this exercise. */
  note: string | null;
  laterality: Laterality;
}

