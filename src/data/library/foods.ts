const NONVEG = new Set<IngredientId>(['chicken', 'mutton', 'fish', 'prawns']);
/** Jain food also leaves out onion, garlic and root vegetables. */
const NOT_JAIN = new Set<IngredientId>([
  ...NONVEG,
  'egg',
  'onion',
  'garlic',
  'ginger',
  'potato',
  'carrot',
  'radish',
  'beetroot',
  'sweet-potato',
]);

const lookup = (id: string): Ingredient => {
  const ing = (INGREDIENTS as Record<string, Ingredient>)[id];
  if (!ing) throw new Error(`Unknown ingredient ${id}`);
  return ing;
};

function dietOf(ids: IngredientId[]): Food['diet'] {
  if (ids.some((i) => NONVEG.has(i))) return 'nonveg';
  if (ids.includes('egg')) return 'egg';
  return 'veg';
}

function fromDish(d: DishDef): Food {
  const lines = d.lines.map(([id, grams]) => ({ id, grams }));
  const cookedG =
    typeof d.cooked === 'number' ? d.cooked : cookedFromMoisture(lines, lookup, d.cooked.moisture);
  const total = sumNutrients(lines.map((l) => ingredientNutrients(lookup(l.id), l.grams)));
  const fatLines = lines.filter((l) => d.fat?.includes(l.id as IngredientId));
  const fatTotal = sumNutrients(fatLines.map((l) => ingredientNutrients(lookup(l.id), l.grams)));
  const per = 100 / cookedG;
  const ids = d.lines.map(([id]) => id);
  return {
    id: d.id,
    name: d.name,
    aliases: d.aliases ?? [],
    category: d.category,
    region: d.region ?? 'north',
    meals: d.meals,
    diet: dietOf(ids),
    jain: !ids.some((i) => NOT_JAIN.has(i)),
    per100: scaleNutrients(total, per),
    fatPer100: fatLines.length ? scaleNutrients(fatTotal, per) : null,
    units: d.units,
    defaultAmount: d.amount ?? 1,
    density: d.density ?? 1,
    pieceG: d.pieces ? cookedG / d.pieces : null,
    pieceName: d.piece ?? null,
    servingG: d.servings ? cookedG / d.servings : null,
    source: 'recipe',
    recipe: {
      lines: lines.map((l) => ({ name: lookup(l.id).name, grams: l.grams })),
      cookedG,
      makes: d.pieces
        ? `${d.pieces} ${d.piece?.[d.pieces > 1 ? 1 : 0] ?? 'pieces'}`
        : `${d.servings ?? 1} servings`,
    },
  };
}

function fromBasic(b: BasicDef): Food {
  const ing = lookup(b.ingredient);
  return {
    id: b.id,
    name: b.name,
    aliases: b.aliases ?? [],
    category: b.category,
    region: b.region ?? 'all',
    meals: b.meals,
    diet: dietOf([b.ingredient]),
    jain: !NOT_JAIN.has(b.ingredient),
    per100: {
      kcal: ing.kcal,
      proteinG: ing.proteinG,
      carbsG: ing.carbsG,
      fatG: ing.fatG,
      fibreG: ing.fibreG,
    },
    fatPer100: null,
    units: b.units,
    defaultAmount: b.amount ?? 1,
    density: b.density ?? 1,
    pieceG: b.pieceG ?? null,
    pieceName: b.piece ?? null,
    servingG: null,
    source: 'ingredient',
    recipe: null,
  };
}

