const lookup = (id: string): Ingredient => {
  const ing = (INGREDIENTS as Record<string, Ingredient>)[id];
  if (!ing) throw new Error(`Unknown ingredient ${id}`);
  return ing;
};

function dietOf(ids: IngredientId[]): Food['diet'] {
  if (ids.some((i) => NONVEG.has(i))) return 'nonveg';
  if (ids.includes('egg') || ids.includes('egg-white')) return 'egg';
  return 'veg';
}

