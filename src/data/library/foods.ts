/** A person's own food or recipe, as a food the logger can use. */
export function customToFood(c: CustomFood): Food {
  const servingG = c.kind === 'recipe' && c.cookedG && c.servings ? c.cookedG / c.servings : null;
  return {
    id: c.id,
    name: c.name,
    aliases: [],
    category: 'basic',
    region: 'all',
    meals: ['breakfast', 'lunch', 'snacks', 'dinner'],
    diet: c.diet,
    jain: false,
    per100: {
      kcal: c.kcal,
      proteinG: c.proteinG,
      carbsG: c.carbsG,
      fatG: c.fatG,
      fibreG: c.fibreG,
    },
    fatPer100: null,
    units: servingG ? ['share', 'katori', 'g'] : c.pieceG ? ['piece', 'g'] : ['g', 'katori'],
    defaultAmount: servingG || c.pieceG ? 1 : 100,
    density: 1,
    pieceG: c.pieceG,
    pieceName: null,
    servingG,
    source: c.kind === 'recipe' ? 'custom_recipe' : 'custom',
    recipe:
      c.kind === 'recipe' && c.ingredients && c.cookedG
        ? {
            lines: c.ingredients.map((l) => ({
              name: (INGREDIENTS as Record<string, Ingredient>)[l.id]?.name ?? l.id,
              grams: l.grams,
            })),
            cookedG: c.cookedG,
            makes: `${c.servings ?? 1} shares`,
          }
        : null,
  };
}

/**
 * Per 100 g of a person's own recipe from its ingredients and the pot's cooked weight. With no
 * cooked weight, the raw weight is used (nothing gained or lost in cooking).
 */
export function recipePer100(lines: { id: string; grams: number }[], cookedG: number | null) {
  const total = sumNutrients(lines.map((l) => ingredientNutrients(lookup(l.id), l.grams)));
  const raw = lines.reduce((s, l) => s + l.grams, 0);
  const weight = cookedG ?? raw;
  return { per100: scaleNutrients(total, 100 / weight), cookedG: weight, rawG: raw };
}

