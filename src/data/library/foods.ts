/**
 * The built-in Indian food library: standard home recipes in grams of raw ingredients, with
 * every value calculated from USDA SR28 ingredient values (`ingredients.ts`). Nothing here is
 * copied from another app or database. Recipes are written for a home kitchen with a normal
 * amount of oil; the oil level in the logger changes the fat named in `fat`.
 *
 * Cooked weights: stated for curries, dals and rice (the pot after cooking), or worked out
 * from the moisture of the cooked food for breads and batters (USDA chapati and naan hold
 * about 33 to 35% water, so breads use 34%).
 *
 * Bump FOOD_LIBRARY_VERSION whenever a value changes; logs keep the numbers they were saved
 * with, so improving a recipe never rewrites anyone's history.
 */
export const FOOD_LIBRARY_VERSION = 1;

type Line = [IngredientId, number];

interface DishDef {
  id: string;
  name: string;
  aliases?: string[];
  category: FoodCategory;
  region?: Region;
  meals: Meal[];
  lines: Line[];
  /** Ingredients that are the cooking fat, changed by the oil level. */
  fat?: IngredientId[];
  /** Grams of the whole pot after cooking, or the moisture of the cooked food. */
  cooked: number | { moisture: number };
  pieces?: number;
  piece?: [string, string];
  servings?: number;
  units: UnitId[];
  amount?: number;
  density?: number;
}

